package ru.ravel.ultunnel.bg

import android.os.SystemClock
import io.nekohasekai.libbox.Connection
import io.nekohasekai.libbox.ConnectionEvents
import io.nekohasekai.libbox.Libbox
import kotlinx.coroutines.CoroutineScope
import ru.ravel.ultunnel.utils.CommandClient

/** Passive per-connection byte deltas from the same source as the Connections screen. */
internal class RecoveryConnectionActivity(scope: CoroutineScope) : CommandClient.Handler {
    data class Snapshot(val hasRecentTraffic: Boolean, val version: Long)
    private data class Counters(var upload: Long, var download: Long)

    private val access = Any()
    private val counters = mutableMapOf<String, Counters>()
    private var running = false
    private var ready = false
    private var version = 0L
    private var lastConnectAt = 0L
    private var lastTrafficAt = -1L
    private val client = CommandClient(
        scope = scope,
        connectionTypes = listOf(CommandClient.ConnectionType.Connections),
        handler = this,
        localOnly = true,
        // Local byte deltas only: no ping, DNS or HTTP request is generated by this subscription.
        statusIntervalMillis = 5_000L,
    )

    fun ensureStarted() {
        val reconnect = synchronized(access) {
            val now = SystemClock.elapsedRealtime()
            if (!running || (!ready && now - lastConnectAt >= 60_000L)) {
                running = true
                ready = false
                counters.clear()
                lastTrafficAt = -1L
                lastConnectAt = now
                true
            } else false
        }
        if (reconnect) client.connect()
    }

    fun stop() {
        synchronized(access) {
            running = false
            ready = false
            counters.clear()
            lastTrafficAt = -1L
            version++
        }
        client.disconnect()
    }

    fun runtimeReloaded() {
        val reconnect = synchronized(access) {
            if (!running) false else {
                ready = false
                counters.clear()
                lastTrafficAt = -1L
                lastConnectAt = SystemClock.elapsedRealtime()
                true
            }
        }
        if (reconnect) client.connect()
    }

    fun activityVersion(): Long = synchronized(access) { version }

    // Historical totals in the initial snapshot are baselines, not evidence of current progress.
    fun snapshot(): Snapshot? = synchronized(access) {
        if (!running || !ready) null else Snapshot(
            lastTrafficAt >= 0L && SystemClock.elapsedRealtime() - lastTrafficAt <= 10_000L,
            version,
        )
    }

    override fun onDisconnected() = invalidate()
    override fun onConnectionError(message: String) = invalidate()

    private fun invalidate() {
        synchronized(access) {
            ready = false
            counters.clear()
            lastTrafficAt = -1L
        }
    }

    private fun isUserConnection(connection: Connection): Boolean =
        connection.outboundType != "dns" && connection.inbound != RecoveryConfig.HEALTH_TAG &&
            !connection.inbound.startsWith("check-in-")

    private fun recordDownloadProgress() {
        // Upload alone may be buffered attempts into a broken tunnel, not proof of a reply.
        lastTrafficAt = SystemClock.elapsedRealtime()
        version++
    }

    override fun writeConnectionEvents(events: ConnectionEvents) {
        synchronized(access) {
            if (!running) return
            if (events.reset) {
                counters.clear()
                lastTrafficAt = -1L
                ready = true
            }
            val iterator = events.iterator()
            while (iterator.hasNext()) {
                val event = iterator.next()
                val id = event.getID()
                when (event.type.toLong()) {
                    Libbox.ConnectionEventNew -> {
                        val connection = event.connection ?: continue
                        if (connection.closedAt != 0L || !isUserConnection(connection)) continue
                        val previous = counters.put(id, Counters(connection.uplinkTotal, connection.downlinkTotal))
                        if (!events.reset && connection.downlinkTotal > (previous?.download ?: 0L)) {
                            recordDownloadProgress()
                        }
                    }
                    Libbox.ConnectionEventUpdate -> {
                        val previous = counters[id] ?: continue
                        previous.upload += event.uplinkDelta.coerceAtLeast(0L)
                        previous.download += event.downlinkDelta.coerceAtLeast(0L)
                        if (event.downlinkDelta > 0L) recordDownloadProgress()
                    }
                    Libbox.ConnectionEventClosed -> {
                        val previous = counters.remove(id) ?: continue
                        val connection = event.connection
                        // Short-lived successful requests may open and close between periodic updates.
                        if (connection != null && isUserConnection(connection) &&
                            connection.downlinkTotal > previous.download
                        ) recordDownloadProgress()
                    }
                }
            }
        }
    }
}
